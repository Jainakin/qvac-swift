#!/usr/bin/env node

// Generate the model-type normalization tables used by Swift loadModel calls
// directly from the exact, hash-locked 0.17 source contract.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..', '..')
const provenance = JSON.parse(readFileSync(resolve(repoRoot, 'tools/provenance/qvac-sdk.lock.json'), 'utf8'))
const upstreamDir = resolve(process.env.QVAC_UPSTREAM_DIR ?? resolve(scriptDir, '.build/qvac-sdk'))
const contractPath = resolve(upstreamDir, 'packages/sdk/contract/model-type-maps.json')
const generatedDir = resolve(process.env.QVAC_GENERATED_DIR
  ?? resolve(repoRoot, 'Sources/QVACClient/Generated'))
const generatedTestDir = resolve(process.env.QVAC_GENERATED_TEST_DIR
  ?? resolve(repoRoot, 'Tests/QVACClientUnitTests'))
const output = resolve(generatedDir, 'QVACModelTypeContract.generated.swift')
const testOutput = resolve(generatedTestDir, 'QVACModelTypeContractTests.generated.swift')
const contract = JSON.parse(readFileSync(contractPath, 'utf8'))
const expectedGroups = ['aliasToCanonical', 'engineToAddon', 'legacyEngineToCanonical']

function fail(message) {
  throw new Error(`[model-type-codegen] ${message}`)
}

function validateMap(name, value) {
  if (!value || Array.isArray(value) || typeof value !== 'object') fail(`${name} must be an object`)
  for (const [key, mapped] of Object.entries(value)) {
    if (!key || typeof mapped !== 'string' || !mapped) fail(`${name} contains a non-string or empty entry`)
  }
}

if (JSON.stringify(Object.keys(contract).sort()) !== JSON.stringify([...expectedGroups].sort())) {
  fail(`unexpected contract groups: ${Object.keys(contract).join(', ')}`)
}
for (const group of expectedGroups) validateMap(group, contract[group])

const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0
const swiftString = value => JSON.stringify(value)
function dictionary(value, indentation = '        ') {
  const entries = Object.entries(value).sort(([a], [b]) => compare(a, b))
  if (entries.length === 0) return '[:]'
  return `[\n${entries.map(([key, mapped]) => `${indentation}${swiftString(key)}: ${swiftString(mapped)},`).join('\n')}\n    ]`
}

const source = `// QVACModelTypeContract.generated.swift
//
// AUTO-GENERATED by tools/codegen/generate-model-type-maps.mjs from:
//   @qvac/sdk@${provenance.sdkVersion} contract/model-type-maps.json
//   gitHead: ${provenance.source.commit}
// Source and npm alias-map parity are verified before generation.
// DO NOT EDIT BY HAND.

internal enum QVACModelTypeContract {
    static let aliasToCanonical: [String: String] = ${dictionary(contract.aliasToCanonical)}

    static let engineToAddon: [String: String] = ${dictionary(contract.engineToAddon)}

    static let legacyEngineToCanonical: [String: String] = ${dictionary(contract.legacyEngineToCanonical)}

    /// Matches @qvac/sdk 0.17 normalizeModelType: built-in aliases are
    /// canonicalized and canonical/custom plugin identifiers pass through.
    static func normalize(_ input: String) -> String {
        aliasToCanonical[input] ?? input
    }
}
`

const tests = `// QVACModelTypeContractTests.generated.swift
//
// AUTO-GENERATED from the exact @qvac/sdk@${provenance.sdkVersion}
// contract/model-type-maps.json at gitHead ${provenance.source.commit}.
// DO NOT EDIT BY HAND.

import XCTest
@testable import QVACClient

final class QVACModelTypeContractTests: XCTestCase {
    func test_all_pinned_maps_are_emitted_exactly() {
        XCTAssertEqual(QVACModelTypeContract.aliasToCanonical, ${dictionary(contract.aliasToCanonical, '            ')})
        XCTAssertEqual(QVACModelTypeContract.engineToAddon, ${dictionary(contract.engineToAddon, '            ')})
        XCTAssertEqual(QVACModelTypeContract.legacyEngineToCanonical, ${dictionary(contract.legacyEngineToCanonical, '            ')})
    }

    func test_normalizer_matches_pinned_alias_semantics_and_preserves_other_values() {
        for (alias, canonical) in QVACModelTypeContract.aliasToCanonical {
            XCTAssertEqual(QVACModelTypeContract.normalize(alias), canonical)
            XCTAssertEqual(QVACModelTypeContract.normalize(canonical), canonical)
        }
        XCTAssertEqual(QVACModelTypeContract.normalize("custom-plugin-model"), "custom-plugin-model")
    }
}
`

mkdirSync(dirname(output), { recursive: true })
mkdirSync(dirname(testOutput), { recursive: true })
writeFileSync(output, source)
writeFileSync(testOutput, tests)
console.log(`Wrote ${Object.keys(contract.aliasToCanonical).length} aliases and source-only model maps -> ${relative(repoRoot, output)}`)
console.log(`Wrote generated model-type contract tests -> ${relative(repoRoot, testOutput)}`)
